// Downloads the recorded gauge height for the replayed storm from USGS and writes
// src/data/gaugeReplay.ts. Run from dashboard/: `node scripts/fetch-gauge.mjs`.

import { writeFileSync } from "node:fs";

const SITE = "11023000"; // San Diego River at Fashion Valley
const START = "2017-02-27T06:00-08:00";
const END = "2017-03-01T06:00-08:00";

const url =
  `https://waterservices.usgs.gov/nwis/iv/?format=json&sites=${SITE}&parameterCd=00065` +
  `&startDT=${encodeURIComponent(START)}&endDT=${encodeURIComponent(END)}`;
const res = await fetch(url);
if (!res.ok) throw new Error(`USGS request failed: ${res.status}`);
const body = await res.json();
const values = body.value.timeSeries[0].values[0].value;
const readings = values.map((v) => [Date.parse(v.dateTime), Number(v.value)]);

const out = `// Generated by scripts/fetch-gauge.mjs — do not edit by hand.
// USGS ${SITE} gauge height (ft) above the gauge datum, 15-minute readings,
// ${new Date(readings[0][0]).toISOString()} to ${new Date(readings.at(-1)[0]).toISOString()}.
export const GAUGE_READINGS: [time: number, stageFt: number][] = [
${readings.map(([t, s]) => `  [${t}, ${s}],`).join("\n")}
];
`;
writeFileSync(new URL("../src/data/gaugeReplay.ts", import.meta.url), out);
console.log(`Wrote ${readings.length} readings`);
