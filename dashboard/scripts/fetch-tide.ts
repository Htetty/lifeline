// Downloads the recorded water level for the San Francisco waterfront's replayed storm from
// NOAA CO-OPS and writes src/data/tideReplay.ts. Run from dashboard/: `npm run fetch:tide`.
//
// Station 9414290 (San Francisco, Golden Gate), hourly heights in metres NAVD88, through the
// Jan 27, 1983 storm tide (the station's record). Readings are interpolated to 15 minutes to
// match the river replay's step, and SEA_LEVEL_RISE_M is added: the scenario is that storm on
// top of a hypothetical metre of sea-level rise. Without it the record tide barely floods.

import { writeFileSync } from "node:fs";

const STATION = "9414290";
const BEGIN = "19830127 00:00";
const END = "19830128 00:00";
export const SEA_LEVEL_RISE_M = 1;
const STEP_MS = 15 * 60_000;

const url =
  "https://api.tidesandcurrents.noaa.gov/api/prod/datagetter?product=hourly_height&datum=NAVD&units=metric" +
  `&time_zone=gmt&format=json&application=hurricaneai&station=${STATION}` +
  `&begin_date=${encodeURIComponent(BEGIN)}&end_date=${encodeURIComponent(END)}`;
const res = await fetch(url);
if (!res.ok) throw new Error(`NOAA request failed: ${res.status}`);
const body = await res.json();
if (body.error) throw new Error(`NOAA: ${body.error.message}`);
const hourly: [number, number][] = body.data
  .filter((d: { v: string }) => d.v !== "")
  .map((d: { t: string; v: string }) => [Date.parse(`${d.t.replace(" ", "T")}:00Z`), Number(d.v)]);

const readings: [number, number][] = [];
for (let i = 0; i < hourly.length - 1; i++) {
  const [t0, v0] = hourly[i];
  const [t1, v1] = hourly[i + 1];
  for (let t = t0; t < t1; t += STEP_MS) {
    const v = v0 + ((v1 - v0) * (t - t0)) / (t1 - t0);
    readings.push([t, Math.round((v + SEA_LEVEL_RISE_M) * 1000) / 1000]);
  }
}
readings.push([hourly.at(-1)![0], Math.round((hourly.at(-1)![1] + SEA_LEVEL_RISE_M) * 1000) / 1000]);

const peak = readings.reduce((best, r, i) => (r[1] > readings[best][1] ? i : best), 0);
writeFileSync(
  new URL("../src/data/tideReplay.ts", import.meta.url),
  `// Generated by scripts/fetch-tide.ts — do not edit by hand.
// NOAA CO-OPS ${STATION} hourly water level (m NAVD88) plus ${SEA_LEVEL_RISE_M} m of hypothetical
// sea-level rise, interpolated to 15 minutes, ${new Date(readings[0][0]).toISOString()} to
// ${new Date(readings.at(-1)![0]).toISOString()}. Peak at index ${peak}.
export const TIDE_SEA_LEVEL_RISE_M = ${SEA_LEVEL_RISE_M};
export const TIDE_READINGS: [time: number, surface: number][] = [
${readings.map(([t, v]) => `  [${t}, ${v}],`).join("\n")}
];
`,
);
console.log(`Wrote ${readings.length} readings; first ${readings[0][1]} m, peak ${readings[peak][1]} m at index ${peak}`);
